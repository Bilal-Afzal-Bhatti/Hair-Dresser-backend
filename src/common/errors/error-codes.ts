import { HttpException, HttpStatus } from '@nestjs/common';

/**
 * Every API error carries a stable `code`. The mobile app translates the code
 * (errors.<CODE> in its language files), so wording lives in one place per language.
 */
export enum ErrorCode {
  VALIDATION_ERROR = 'VALIDATION_ERROR',
  UNAUTHORIZED = 'UNAUTHORIZED',
  FORBIDDEN = 'FORBIDDEN',
  NOT_FOUND = 'NOT_FOUND',
  TOO_MANY_REQUESTS = 'TOO_MANY_REQUESTS',
  INTERNAL_ERROR = 'INTERNAL_ERROR',

  EMAIL_ALREADY_EXISTS = 'EMAIL_ALREADY_EXISTS',
  PHONE_ALREADY_EXISTS = 'PHONE_ALREADY_EXISTS',
  INVALID_CREDENTIALS = 'INVALID_CREDENTIALS',
  EMAIL_NOT_VERIFIED = 'EMAIL_NOT_VERIFIED',
  EMAIL_ALREADY_VERIFIED = 'EMAIL_ALREADY_VERIFIED',
  OTP_INVALID = 'OTP_INVALID',
  OTP_EXPIRED = 'OTP_EXPIRED',
  OTP_TOO_MANY_ATTEMPTS = 'OTP_TOO_MANY_ATTEMPTS',
  OTP_RESEND_TOO_SOON = 'OTP_RESEND_TOO_SOON',
  RESET_TOKEN_INVALID = 'RESET_TOKEN_INVALID',
  REFRESH_TOKEN_INVALID = 'REFRESH_TOKEN_INVALID',
  LANGUAGE_NOT_SUPPORTED = 'LANGUAGE_NOT_SUPPORTED',
  SALON_NOT_FOUND = 'SALON_NOT_FOUND',

  WRONG_PASSWORD = 'WRONG_PASSWORD',
  SERVICE_NOT_FOUND = 'SERVICE_NOT_FOUND',
  SPECIALIST_NOT_FOUND = 'SPECIALIST_NOT_FOUND',
  DATE_OUT_OF_RANGE = 'DATE_OUT_OF_RANGE',
  SLOT_UNAVAILABLE = 'SLOT_UNAVAILABLE',
  BOOKING_NOT_FOUND = 'BOOKING_NOT_FOUND',
  BOOKING_NOT_CANCELLABLE = 'BOOKING_NOT_CANCELLABLE',
  INVALID_STATUS_CHANGE = 'INVALID_STATUS_CHANGE',
  COUPON_INVALID = 'COUPON_INVALID',
  COUPON_EXPIRED = 'COUPON_EXPIRED',
  COUPON_MIN_NOT_MET = 'COUPON_MIN_NOT_MET',
  COUPON_ALREADY_USED = 'COUPON_ALREADY_USED',
  REVIEW_NOT_ALLOWED = 'REVIEW_NOT_ALLOWED',
  REVIEW_ALREADY_EXISTS = 'REVIEW_ALREADY_EXISTS',

  AVATAR_INVALID = 'AVATAR_INVALID',
  FILE_TOO_LARGE = 'FILE_TOO_LARGE',
}

export class AppException extends HttpException {
  constructor(
    public readonly code: ErrorCode,
    status: HttpStatus,
    message?: string,
    public readonly details?: Record<string, unknown>,
  ) {
    super({ code, message: message ?? code, details }, status);
  }
}